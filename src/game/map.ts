export interface SectorInfo {
  id: 'A' | 'B' | 'C' | 'D';
  name: string;
  hint: string;
}

export function sectorAt(x: number, y: number, hasCore: boolean): SectorInfo {
  const tx = Math.floor(x / 16);
  const ty = Math.floor(y / 16);
  if (ty <= 10 && hasCore) {
    return {
      id: 'D',
      name: 'SECTOR D · LOCKDOWN EXTRACTION',
      hint: 'Core recovered — fight left to the Extraction Airlock! (Q / Right-Click: Rail-Slug)',
    };
  }
  if (tx >= 83 && ty >= 11) {
    return {
      id: 'C',
      name: tx >= 106 ? 'SECTOR C · REACTOR VAULT' : 'SECTOR C · BLACKOUT SHAFT',
      hint: tx >= 106
        ? 'Defeat the Core Warden and seize the Power Core! (Q / Right-Click: piercing Rail-Slug)'
        : 'Press E to toggle headlamp · Climb the shaft toward the Reactor Vault',
    };
  }
  if (tx >= 30 && ty > 10) {
    return {
      id: 'B',
      name: 'SECTOR B · BIO-CONDUIT HALL',
      hint: 'Jump bio-sludge grates · Watch high Spore-Sentinels charging plasma orbs',
    };
  }
  return {
    id: 'A',
    name: 'SECTOR A · CALIBRATION AIRLOCK',
    hint: 'A/D move · Space jump · Left-Click pulse · Q/Right-Click rail-slug · E headlamp',
  };
}
